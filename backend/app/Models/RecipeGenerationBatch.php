<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

class RecipeGenerationBatch extends Model
{
    public const STATUS_CREATED = 'created';

    public const STATUS_RUNNING = 'running';

    public const STATUS_COMPLETED = 'completed';

    public const STATUS_EXHAUSTED = 'exhausted';

    public const STATUS_FAILED = 'failed';

    public const STATUS_CANCELLED = 'cancelled';

    protected $fillable = [
        'requested_count',
        'cuisine',
        'dish_family',
        'category',
        'params',
        'status',
        'accepted_count',
        'rejected_count',
        'failed_count',
        'generation_attempts',
        'max_attempts',
        'lease_expires_at',
        'error',
        'started_at',
        'finished_at',
    ];

    protected function casts(): array
    {
        return [
            'params' => 'array',
            'requested_count' => 'integer',
            'accepted_count' => 'integer',
            'rejected_count' => 'integer',
            'failed_count' => 'integer',
            'generation_attempts' => 'integer',
            'max_attempts' => 'integer',
            'lease_expires_at' => 'datetime',
            'started_at' => 'datetime',
            'finished_at' => 'datetime',
        ];
    }

    /** Accepted recipes generated by this batch. */
    public function items(): HasMany
    {
        return $this->hasMany(RecipeGenerationBatchItem::class, 'batch_id');
    }

    public function duplicateChecks(): HasMany
    {
        return $this->hasMany(DuplicateCheck::class, 'batch_id');
    }

    public function remainingTarget(): int
    {
        return max(0, $this->requested_count - $this->accepted_count);
    }

    public function isTerminal(): bool
    {
        return in_array($this->status, [
            self::STATUS_COMPLETED,
            self::STATUS_EXHAUSTED,
            self::STATUS_FAILED,
            self::STATUS_CANCELLED,
        ], true);
    }

    /**
     * Atomic single-worker lease: take row lock and claim the batch for
     * $seconds when it is unclaimed or its lease expired, Report whether
     * THIS call won the claim. Returns false for terminal states.
     */
    public function claimLease(int $seconds): bool
    {
        $fresh = static::query()->find($this->getKey());

        if ($fresh === null) {
            return false;
        }

        if ($fresh->isTerminal()) {
            return false;
        }

        $claimed = static::query()
            ->whereKey($fresh->getKey())
            ->where(function (Builder $query): void {
                $query->whereNull('lease_expires_at')
                    ->orWhere('lease_expires_at', '<', now());
            })
            ->whereNotIn('status', [
                self::STATUS_COMPLETED,
                self::STATUS_EXHAUSTED,
                self::STATUS_FAILED,
                self::STATUS_CANCELLED,
            ])
            ->update(['lease_expires_at' => Carbon::now()->addSeconds($seconds)]);

        if ($claimed > 0) {
            $this->forceFill([
                'lease_expires_at' => Carbon::now()->addSeconds($seconds),
                'status' => self::STATUS_RUNNING,
                'started_at' => $this->started_at ?? Carbon::now(),
            ])->save();

            return true;
        }

        $this->refresh();

        return false;
    }

    public function releaseLease(): void
    {
        $this->forceFill(['lease_expires_at' => null])->save();
    }
}
